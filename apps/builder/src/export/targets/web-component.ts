// A <formsgen-form> element for any page: the renderer's own custom element
// (packages/renderer/src/element.ts, built into dist/element/) rendering the
// form from its project file. The export is a host page plus the project
// file; the element script joins it when the caller has it (the builder
// fetches its own copy, the CLI reads the renderer's build), else the README
// says where to get it.

import { escapeHtml } from '../structure'
import type { ExportTarget, ExportedFile } from './types'

export const ELEMENT_SCRIPT = 'formsgen-element.js'

export const webComponentTarget: ExportTarget = {
  id: 'web-component',
  label: 'Web Component (any page)',
  description: 'A <formsgen-form> element: one script tag renders the form in any site, no framework needed.',
  frameworkAware: false,
  generate: ({ schema, assets }) => {
    const name = schema.meta.name
    const title = schema.meta.title ?? name
    const scriptSrc = assets?.elementScript ? `./${ELEMENT_SCRIPT}` : (assets?.elementScriptUrl ?? `./${ELEMENT_SCRIPT}`)
    const page = `<!doctype html>
<html lang="${escapeHtml(schema.meta.locale)}" dir="${schema.meta.dir}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${escapeHtml(title)}</title>
  <!-- Generated by FormsGen: the form as a web component. -->
  <script type="module" src="${escapeHtml(scriptSrc)}"></script>
  <style>
    body { margin: 0; padding: 2rem 1rem; font-family: system-ui, sans-serif; background: #f1f5f9; }
    formsgen-form { display: block; max-width: 720px; margin: 0 auto; }
  </style>
</head>
<body>
  <formsgen-form src="./${escapeHtml(name)}.formsgen.json"></formsgen-form>
  <script type="module">
    // The element sends the answers where the form's Submit setting points
    // (or nowhere) and tells the page what happened. Call event.preventDefault()
    // on formsgen-submit to send them yourself.
    const form = document.querySelector('formsgen-form')
    form.addEventListener('formsgen-submit', (event) => console.log('submitted', event.detail))
    form.addEventListener('formsgen-sent', (event) => console.log('server said', event.detail))
  </script>
</body>
</html>
`
    const files: ExportedFile[] = [{ path: `${name}.html`, content: page, language: 'xml' }]
    if (assets?.elementScript) files.push({ path: ELEMENT_SCRIPT, content: assets.elementScript, language: 'javascript', project: false })
    return files
  },
  readme: ({ schema, assets }) => {
    const name = schema.meta.name
    const where = assets?.elementScript
      ? `\`${ELEMENT_SCRIPT}\` is in this package.`
      : `Copy \`${ELEMENT_SCRIPT}\` from \`@formsgen/renderer\` (\`dist/element/\`, built with \`pnpm --filter @formsgen/renderer build:element\`) next to the page${assets?.elementScriptUrl ? `, or load it from \`${assets.elementScriptUrl}\`` : ''}.`
    return `# ${schema.meta.title ?? name} (web component)

One script, one tag, any page — no framework on the page is needed:

\`\`\`html
<script type="module" src="./${ELEMENT_SCRIPT}"></script>
<formsgen-form src="./${name}.formsgen.json"></formsgen-form>
\`\`\`

${where} \`${name}.html\` is a page to start from.

## The element

- **\`src\`** — the URL of the project file (\`.formsgen.json\`); or set the
  \`schema\` property to the project object (\`form.schema = …\`), or the
  \`schema\` attribute to its JSON text.
- **\`theme="light"\` / \`"dark"\`** pins the colour scheme; without it the
  form follows its own theme and the visitor's system.
- Everything the form does in the builder's preview works here: rules,
  conditions, calculations, uploads, drafts, the spam check, prefill from
  the page address, the thank-you or redirect after submit.

## Events (all bubble)

- **\`formsgen-change\`** — \`detail\`: the answers so far.
- **\`formsgen-submit\`** — \`detail\`: the validated answers. The element
  then sends them to the form's submit URL (JSON, or multipart with
  uploads); \`event.preventDefault()\` keeps that for your own code.
- **\`formsgen-sent\`** — \`detail: { ok, status }\` once the server answered.
- **\`formsgen-ready\`** / **\`formsgen-error\`** — the project loaded, or not
  (\`detail\`: the reasons).

The script is self-contained (Vue included) and adds the form's stylesheet
to the page once; the form renders in the page itself (no shadow DOM), so
your own CSS can style it through its \`fg-\` classes.
`
  },
}
