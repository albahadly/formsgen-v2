import { servicesReadme } from '../readmeNotes'
import { afterSubmitOf } from '../afterSubmit'
import { componentName, type ExportTarget } from './types'

export const vueLibTarget: ExportTarget = {
  id: 'vue-lib',
  label: 'Vue (renderer package)',
  description: 'A small SFC using @albahadly/formsgen-renderer — schema-driven, always in sync.',
  frameworkAware: false,
  generate: ({ schema }) => {
    const name = componentName(schema)
    const schemaLiteral = JSON.stringify(schema, null, 2).replace(/\n/g, '\n')
    const submit = schema.meta.submit
    const after = afterSubmitOf(schema)
    const thanksLib = after.message !== null && after.redirectUrl === null
    // After a successful send: the page goes on, or the thank-you replaces the form.
    const afterLines = after.redirectUrl !== null ? `\n  window.location.assign(${JSON.stringify(after.redirectUrl)})` : thanksLib ? '\n  sent.value = true' : ''
    // The renderer only validates and emits; sending is the wrapper's job.
    // With a submit URL set in the builder the wrapper sends there, like the
    // other targets do (JSON, or multipart when the form has uploads).
    const imports = submit?.url ? 'FormsGenForm, hasUploadFields, sendSubmission, type FormSchema' : 'FormsGenForm, type FormSchema'
    const onSubmit = submit?.url
      ? `async function onSubmit(payload: Record<string, unknown>): Promise<void> {
  // Sent where the form's Submit setting points; replace with your own handling.
  const result = await sendSubmission(${JSON.stringify(submit.url)}, payload, {
    method: ${JSON.stringify(submit.method ?? 'POST')},
    multipart: hasUploadFields(schema.tree),${submit.headers && Object.keys(submit.headers).length ? `\n    headers: ${JSON.stringify(submit.headers)},` : ''}
  })
${afterLines ? `  if (!result.ok) {\n    console.error('${name}: the server did not accept the submission', result.status)\n    return\n  }${afterLines}` : `  if (!result.ok) console.error('${name}: the server did not accept the submission', result.status)`}
}`
      : `function onSubmit(payload: Record<string, unknown>): void {
  // Replace with your submit handling.
  console.log('${name} submitted', payload)${afterLines}
}`
    return [
      {
        path: `${name}.vue`,
        language: 'xml',
        content: `<script setup lang="ts">
// Generated by FormsGen. Renders via @albahadly/formsgen-renderer.
import { ref } from 'vue'
import { ${imports} } from '@albahadly/formsgen-renderer'
import '@albahadly/formsgen-renderer/style.css'

const schema = ${schemaLiteral} as unknown as FormSchema

const data = ref<Record<string, unknown>>({})
${thanksLib ? `\n// After submit: the thank-you replaces the form until "Send another response".\nconst sent = ref(false)\n` : ''}
${onSubmit}
</script>

<template>
  <FormsGenForm
    v-model="data"
    :schema="schema"${thanksLib ? `\n    :sent="sent"` : ''}
    @submit="onSubmit"${thanksLib ? `\n    @again="sent = false"` : ''}
  />
</template>
`,
      },
    ]
  },
  readme: ({ schema }) => `# ${componentName(schema)} (Vue 3, @albahadly/formsgen-renderer)

## Install

1. Install the renderer in your Vue 3 project:
   \`npm i @albahadly/formsgen-renderer\`
   (or build and pack it from the FormsGen monorepo:
   \`pnpm --filter @albahadly/formsgen-renderer build && pnpm --filter @albahadly/formsgen-renderer pack\`,
   then \`npm i ./albahadly-formsgen-renderer-*.tgz\`)
2. Drop \`${componentName(schema)}.vue\` anywhere in your app and use it:

\`\`\`html
<${componentName(schema)} />
\`\`\`

Styling is the renderer's self-contained vanilla theme (dark-mode and RTL
aware, themeable via \`meta.theme\` tokens in the schema). Validation and
conditional visibility run inside the renderer — edit the schema, not the
component, to change behavior.
${schema.meta.submit?.url ? `\nOn valid submit the wrapper's \`onSubmit\` sends the payload to \`${schema.meta.submit.url}\` with the renderer's \`sendSubmission\` (JSON, or multipart when the form has uploads); edit it for your own handling.` : `\nThe renderer validates and emits \`submit\` with the answers; the wrapper's \`onSubmit\` is where you send them (set a submit URL in the builder to have it generated).`}
${servicesReadme(schema, 'vue-lib')}`,
}
